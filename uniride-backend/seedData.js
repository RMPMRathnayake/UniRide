// 7. DATABASE INITIALIZATION & SEEDER FUNCTION (`seedDatabase`)
// ============================================================================
export async function seedDatabase() {
  const storeDocs = ALL_STORES.map((store) => ({
    ...store,
    _id: store.id,
    storeType: store.storeType || 'demonstration',
    isIndependent: false,
    location: {
      dLat: store.dLat ?? 0.008,
      dLng: store.dLng ?? 0.006,
      streetAddress: store.streetAddress || '',
    },
  }));

  const productDocs = [];
  for (const store of ALL_STORES) {
    const templateKey = store.templateKey || 'grocery';
    const baseTemplate =
      CATEGORY_PRODUCT_TEMPLATES[templateKey] || CATEGORY_PRODUCT_TEMPLATES.grocery;
    const factor = store.priceFactor ?? 1.0;

    for (const tpl of baseTemplate) {
      const computedPrice =
        factor === 1.0 ? tpl.basePrice : Math.round((tpl.basePrice * factor) / 5) * 5;
      const productId = `${store.id}-${tpl.id}`;

      productDocs.push({
        _id: productId,
        id: productId,
        storeId: store.id,
        storeName: store.name,
        category: store.category,
        templateKey,
        name: tpl.name,
        price: computedPrice,
        basePrice: tpl.basePrice,
        tag: tpl.tag,
        rankBadge: tpl.rankBadge || null,
        likesPct: tpl.likesPct ?? 90,
        likesCount: tpl.likesCount ?? 120,
        desc:
          tpl.desc ||
          'Freshly prepared and packed with care for fast UniRide delivery.',
        img: tpl.img,
      });
    }
  }

  const riderDocs = UNIRIDE_RIDERS.map((rider, index) => ({
    ...rider,
    _id: rider.id,
    isOnline: true,
    isAvailable: true,
    activeOrderId: null,
    lastKnownLocation: {
      type: 'Point',
      coordinates: [81.8505 + index * 0.001, 7.2975 + index * 0.001],
    },
    lastLocationUpdatedAt: new Date(),
    demoLedgerBalanceMinor: 0,
  }));

  const masterCatalogDocs = CONCIERGE_MASTER_CATALOG_TEMPLATES.map((tpl) => ({
    ...tpl,
    _id: tpl.id,
  }));

  const allSeededDiscoveredShops = [
    ...SEUSL_CAMPUS_DISCOVERED_SHOPS,
    ...KADAWATHA_DISCOVERED_SHOPS,
  ];

  const groups = [
    [Store, storeDocs],
    [Product, productDocs],
    [Rider, riderDocs],
    [Location, LOCATION_SUGGESTIONS.map((location) => ({ ...location, _id: location.id }))],
    [MasterCatalogItem, masterCatalogDocs],
    [DiscoveredShop, allSeededDiscoveredShops],
  ];

  const now = new Date();
  const prepared = [];
  for (const [Model, docs] of groups) {
    const validated = [];
    for (const doc of docs) {
      const instance = new Model({ ...doc, createdAt: now, updatedAt: now });
      await instance.validate();
      validated.push(instance.toObject({ versionKey: false }));
    }
    prepared.push([Model, validated]);
  }

  const summary = {};
  for (const [Model, docs] of prepared) {
    const result = docs.length
      ? await Model.bulkWrite(
          docs.map((doc) => ({
            updateOne: {
              filter: { [doc.externalId ? 'externalId' : 'id']: doc.externalId || doc.id },
              update: { $setOnInsert: doc },
              upsert: true,
              timestamps: false,
            },
          })),
          { ordered: true }
        )
      : { upsertedCount: 0, matchedCount: 0 };

    summary[Model.collection.name] = {
      added: result.upsertedCount,
      alreadyPresent: result.matchedCount,
      total: await Model.countDocuments(),
    };
  }

  // Seed initial discovery cache buckets for SEUSL campus (7.2974, 81.8504) AND Kadawatha (7.0682, 79.9670)
  const seuslBucket = computeCoveringBucket(7.2974, 81.8504, 3000);
  await DiscoveryCache.findOneAndUpdate(
    { bucketKey: seuslBucket.bucketKey },
    {
      $setOnInsert: {
        _id: seuslBucket.bucketKey,
        bucketKey: seuslBucket.bucketKey,
        centerLat: seuslBucket.centerLat,
        centerLng: seuslBucket.centerLng,
        fetchedRadiusMeters: seuslBucket.fetchRadiusMeters,
        shopExternalIds: SEUSL_CAMPUS_DISCOVERED_SHOPS.map((s) => s.externalId),
        fetchedAt: now,
        expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000),
      },
    },
    { upsert: true, new: true }
  );

  const kadawathaBucket = computeCoveringBucket(7.0682, 79.9670, 3000);
  await DiscoveryCache.findOneAndUpdate(
    { bucketKey: kadawathaBucket.bucketKey },
    {
      $setOnInsert: {
        _id: kadawathaBucket.bucketKey,
        bucketKey: kadawathaBucket.bucketKey,
        centerLat: kadawathaBucket.centerLat,
        centerLng: kadawathaBucket.centerLng,
        fetchedRadiusMeters: kadawathaBucket.fetchRadiusMeters,
        shopExternalIds: KADAWATHA_DISCOVERED_SHOPS.map((s) => s.externalId),
        fetchedAt: now,
        expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000),
      },
    },
    { upsert: true, new: true }
  );

  await Rider.updateMany(
    { isOnline: { $exists: false } },
    {
      $set: {
        isOnline: true,
        isAvailable: true,
        activeOrderId: null,
        lastKnownLocation: {
          type: 'Point',
          coordinates: [81.8505, 7.2975],
        },
        lastLocationUpdatedAt: now,
        demoLedgerBalanceMinor: 0,
      },
    }
  );

  console.log('Sample data initialized. Existing data and orders were preserved.');
  console.table(summary);
  return summary;
}