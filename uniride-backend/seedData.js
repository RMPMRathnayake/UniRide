export function calculateRoadDistanceKm(lat1, lng1, lat2, lng2) {
  if (!lat1 || !lng1 || !lat2 || !lng2) return 1.8;
  const R = 6371;
  const toRad = (deg) => (deg * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  const straightKm = 2 * R * Math.asin(Math.sqrt(a));
  const roadKm = Math.max(0.6, straightKm * 1.3);
  return Number(roadKm.toFixed(1));
}

export function calculateDynamicEtaMins(distanceKm, prepTimeMins = 10, riderBufferMins = 3) {
  const travelMins = Math.ceil((distanceKm / 25) * 60);
  return prepTimeMins + travelMins + riderBufferMins;
}

